krotka = tuple(range(5))
krotka += ("pięć", "sześć", "siedem", "osiem", "dziewięć")

print(*krotka[:3])
print(*krotka[-2:])
print(*krotka[1::2])
print(f"Długość krotki: {len(krotka)}, długość przedostatniego elementu: {len(krotka[-2])}")
print(krotka[:5] + (5,6) + krotka[-3:])
print(krotka[:5], (5,6), krotka[-3:])
krotka += ("",)